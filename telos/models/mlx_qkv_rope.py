"""Opt-in QKV unpack, traditional RoPE and head permutation for Metal training.

Adapted from the supplied Gemini proposal and checked locally on MLX 0.32.2.
Supports equal Q/K/V head counts, head dimension 64 and first-order VJP only.
The FP32 trig table is constant, not a model parameter. It is generated by the
built-in MLX RoPE kernel. This module does not change checkpoint parameter shapes.
"""
import mlx.core as mx

_FORWARD = mx.fast.metal_kernel(
    name="telos_experimental_qkv_rope_forward",
    input_names=["qkv", "cos_sin"], output_names=["q_out", "k_out", "v_out"],
    ensure_row_contiguous=True,
    source=r"""
   uint elem = thread_position_in_grid.x;
   // Fixed head_dim = 64 -> half_dim = 32 (one SIMD group = 1 full head row!)
   const uint half_dim = 32;
   const uint head_dim = 64;

   if (elem >= qkv_shape[0] * qkv_shape[1] * qkv_shape[2] / 6) return;
   uint T = (uint)qkv_shape[1];
   uint total_qkv = (uint)qkv_shape[2];
   uint H = total_qkv / (3 * head_dim);

   uint p = elem & 31u;                 // pair index 0..31
   uint row_idx = elem >> 5;            // (b * H + h) * T + t
   uint t = row_idx % T;
   uint bh = row_idx / T;
   uint h = bh % H;
   uint b = bh / H;

   uint q_chunk_stride = H * head_dim; // 512 for H=8, Dh=64
   uint qkv_row_base = (b * T + t) * total_qkv;
   uint head_offset = h * head_dim + (p << 1);

   uint q_in_idx = qkv_row_base + head_offset;
   uint k_in_idx = q_in_idx + q_chunk_stride;
   uint v_in_idx = k_in_idx + q_chunk_stride;

   // Load [t, p, 0..1] from cos_sin table: shape [T, 32, 2]
   uint cs_idx = ((t << 5) + p) << 1;
   float c = cos_sin[cs_idx];
   float s = cos_sin[cs_idx + 1];

   // Read Q pair and rotate in FP32
   float q0 = static_cast<float>(qkv[q_in_idx]);
   float q1 = static_cast<float>(qkv[q_in_idx + 1]);
   float q_rot0 = q0 * c - q1 * s;
   float q_rot1 = q0 * s + q1 * c;

   // Read K pair and rotate in FP32
   float k0 = static_cast<float>(qkv[k_in_idx]);
   float k1 = static_cast<float>(qkv[k_in_idx + 1]);
   float k_rot0 = k0 * c - k1 * s;
   float k_rot1 = k0 * s + k1 * c;

   // Read V pair (no rotation, pure coalesced transpose)
   T_io v0 = qkv[v_in_idx];
   T_io v1 = qkv[v_in_idx + 1];

   // Output index in [B, H, T, 64] is simply (elem << 1)
   uint out_idx = elem << 1;
   q_out[out_idx]     = static_cast<T_io>(q_rot0);
   q_out[out_idx + 1] = static_cast<T_io>(q_rot1);
   k_out[out_idx]     = static_cast<T_io>(k_rot0);
   k_out[out_idx + 1] = static_cast<T_io>(k_rot1);
   v_out[out_idx]     = v0;
   v_out[out_idx + 1] = v1;
""",
)

_BACKWARD = mx.fast.metal_kernel(
    name="telos_experimental_qkv_rope_backward",
    input_names=["dq", "dk", "dv", "cos_sin"], output_names=["dqkv"],
    ensure_row_contiguous=True,
    source=r"""
   uint elem = thread_position_in_grid.x;
   // Each thread handles one pair (2*p, 2*p+1) for a specific (b, h, t)
   const uint head_dim = 64;

   if (elem >= dq_shape[0] * dq_shape[1] * dq_shape[2] * 32) return;
   uint H = (uint)dq_shape[1];
   uint T = (uint)dq_shape[2];
   uint q_chunk_stride = H * head_dim;
   uint total_qkv = 3 * q_chunk_stride;

   uint p = elem & 31u;
   uint row_idx = elem >> 5;            // (b * H + h) * T + t
   uint t = row_idx % T;
   uint bh = row_idx / T;
   uint h = bh % H;
   uint b = bh / H;

   // Coalesced read from [B, H, T, 64]
   uint in_idx = elem << 1;
   float dq0 = static_cast<float>(dq[in_idx]);
   float dq1 = static_cast<float>(dq[in_idx + 1]);
   float dk0 = static_cast<float>(dk[in_idx]);
   float dk1 = static_cast<float>(dk[in_idx + 1]);
   T_io dv0 = dv[in_idx];
   T_io dv1 = dv[in_idx + 1];

   // Load cos/sin for (t, p)
   uint cs_idx = ((t << 5) + p) << 1;
   float c = cos_sin[cs_idx];
   float s = cos_sin[cs_idx + 1];

   // Inverse rotation (R(theta)^T = R(-theta)) in FP32
   // Keep operation order aligned with MLX's traditional RoPE VJP.
   float dq_in0 = dq1 * s + dq0 * c;
   float dq_in1 = dq1 * c - dq0 * s;
   float dk_in0 = dk1 * s + dk0 * c;
   float dk_in1 = dk1 * c - dk0 * s;

   // Coalesced write into [B, T, 3 * H * 64]
   uint qkv_row_base = (b * T + t) * total_qkv;
   uint head_offset = h * head_dim + (p << 1);

   uint q_out_idx = qkv_row_base + head_offset;
   uint k_out_idx = q_out_idx + q_chunk_stride;
   uint v_out_idx = k_out_idx + q_chunk_stride;

   dqkv[q_out_idx]     = static_cast<T_io>(dq_in0);
   dqkv[q_out_idx + 1] = static_cast<T_io>(dq_in1);
   dqkv[k_out_idx]     = static_cast<T_io>(dk_in0);
   dqkv[k_out_idx + 1] = static_cast<T_io>(dk_in1);
   dqkv[v_out_idx]     = dv0;
   dqkv[v_out_idx + 1] = dv1;
""",
)


def make_rope_table(sequence_length):
    """Build an [T,32,2] FP32 cosine/sine table using MLX's RoPE kernel itself.

    At T=256 the combined table is 64 KiB. A rotated basis vector yields the
    exact constants used by ``mx.fast.rope`` for this runtime and device.
    """
    if sequence_length < 1:
        raise ValueError("sequence_length must be positive")
    basis = mx.broadcast_to(mx.array([1.0, 0.0], dtype=mx.float32),
                            (sequence_length, 32, 2)).reshape(1, 1, sequence_length, 64)
    rotated = mx.fast.rope(basis, 64, traditional=True, base=10000.0,
                           scale=1.0, offset=0).reshape(sequence_length, 32, 2)
    table = mx.stack([rotated[:, :, 0], rotated[:, :, 1]], axis=-1)
    mx.eval(table)
    return table


@mx.custom_function
def _qkv_rope(qkv, table):
    batch, sequence, width = qkv.shape
    heads = width // 192
    shape = (batch, heads, sequence, 64)
    return tuple(_FORWARD(
        inputs=[qkv, table], template=[("T_io", qkv.dtype)],
        grid=(batch * heads * sequence * 32, 1, 1), threadgroup=(256, 1, 1),
        output_shapes=[shape, shape, shape], output_dtypes=[qkv.dtype] * 3,
    ))


@_qkv_rope.vjp
def _qkv_rope_vjp(primals, cotangents, outputs):
    qkv, table = primals
    dq, dk, dv = cotangents
    batch, heads, sequence, _ = dq.shape
    gradient = _BACKWARD(
        inputs=[dq, dk, dv, table], template=[("T_io", dq.dtype)],
        grid=(batch * heads * sequence * 32, 1, 1), threadgroup=(256, 1, 1),
        output_shapes=[qkv.shape], output_dtypes=[qkv.dtype],
    )[0]
    return gradient, mx.zeros_like(table)


def experimental_qkv_rope(qkv, table):
    """Unpack equal-head QKV into [B,H,T,64], rotating Q/K at offset zero."""
    if qkv.ndim != 3 or qkv.shape[-1] == 0 or qkv.shape[-1] % 192:
        raise ValueError("Expected packed equal-head QKV with head dimension 64")
    if table.shape != (qkv.shape[1], 32, 2) or table.dtype != mx.float32:
        raise ValueError("Expected an FP32 [sequence,32,2] RoPE table")
    if qkv.dtype not in (mx.float32, mx.bfloat16):
        raise ValueError("Experimental QKV RoPE supports float32 and bfloat16 only")
    return _qkv_rope(qkv, table)
